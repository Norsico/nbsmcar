uint8 getImagePointFilterSelf(uint8 i, uint8 j) {
    if (i > 90 && j >= 48 && j <= 140) return 255;
    return mt9v03x_image[i][j];
}

uint8 getPointThreshold(uint8 x, uint8 y) {
    uint16 total = 0;
    uint8 i, j;
    for (i = x - halfBlock; i <= x + halfBlock; i++)
        for (j = y - halfBlock; j <= y + halfBlock; j++)
            total += mt9v03x_image[i][j];
    return total / (block * block) - cap;
}

static int8 check(uint8 x, uint8 y) {
    uint16 d = func_abs((int16) mt9v03x_image[x][y - 2] - (int16) mt9v03x_image[x][y + 2]), a =
            (uint16) mt9v03x_image[x][y - 2] + (uint16) mt9v03x_image[x][y + 2];
    if (d > 15 && a / d <= 7) return 1;
    return 0;
}

static int16 getLIndexStart(int16 i) {
    int16 l, r, m;
    l = halfBlock + 1;
    r = i < 90 ? halfW : 48;
    while (l < r) {
        m = (l + r) >> 1;
        if (mt9v03x_image[i][m] < LThreshold && mt9v03x_image[i][func_max(0, m - 8)] < LThreshold && mt9v03x_image[i][func_max(0, m - 25)] < LThreshold) l = m + 1;
        else r = m;
    }
    return l;
}

Point getLStart() {
    int16 i, l;
    Point ans;
    for (i = MT9V03X_H - halfBlock - 2; i >= 70; i -= 3) {
        l = getLIndexStart(i);
        if (mt9v03x_image[i][func_min(l + 2, 187)] > LThreshold && check(i, l)) {
            ans.x = i;
            ans.y = l + 1;
            return ans;
        }
    }
    ans.x = 0;
    ans.y = 0;
    return ans;
}

static int16 getRIndexStart(int16 i) {
    int16 l, r, m;
    l = i < 90 ? halfW : 140;
    r = 186 - halfBlock;
    while (l < r) {
        m = (l + r + 1) >> 1;
        if (mt9v03x_image[i][m] < RThreshold && mt9v03x_image[i][func_min(187, m + 8)] < RThreshold && mt9v03x_image[i][func_min(187, m + 25)] < RThreshold) r = m - 1;
        else l = m;
    }
    return r;
}

Point getRStart() {
    int16 i, r;
    Point ans;
    for (i = MT9V03X_H - halfBlock - 2; i >= 70; i -= 3) {
        r = getRIndexStart(i);
        if (mt9v03x_image[i][func_max(r - 2, 0)] > RThreshold && check(i, r)) {
            ans.x = i;
            ans.y = r - 1;
            return ans;
        }
    }
    ans.x = 0;
    ans.y = 0;
    return ans;
}

